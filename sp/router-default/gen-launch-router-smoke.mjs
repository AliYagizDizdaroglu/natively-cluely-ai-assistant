// gen-launch-router-smoke.mjs: writes launch-router-smoke.cmd (Task 17) and reads it back byte by byte.
// ASCII, CRLF, never edited by hand and never with sed. Run: node gen-launch-router-smoke.mjs [--out DIR]
// The smoke runs the app hour only (no flight.mjs): wav:check, then interview60.run.mjs auto router-smoke.
// Keys: the flight-eq launcher has no key wrapper (the app reads its own credentials), so none here and no key is read or printed.
// MAIN has a non-ASCII folder (Masa + u-umlaut + stu): the file stays ASCII, the cd finds it by wildcard like register-rd.ps1 does.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const outDir = path.resolve(args.includes('--out') ? args[args.indexOf('--out') + 1] : HERE);
const FILE = path.join(outDir, 'launch-router-smoke.cmd');

const SET = ['NATIVELY_LIVE_ROUTER=1', 'NATIVELY_ROSTER=live40', 'NATIVELY_STT_PROVIDER=deepgram'];
// the flight-eq cleared names (minus the ones it SETS) plus the four extra
const CLEAR = ['NATIVELY_GEMINI_THINKING_LEVEL', 'NATIVELY_VERBAL_PRIMARY_MODEL', 'NATIVELY_VERBAL_HEDGE', 'NATIVELY_VERBAL_HEDGE_TRIGGER_MS',
  'NATIVELY_FOLLOWUP_PARENT', 'NATIVELY_LIVE_MODEL', 'NATIVELY_LIVE_MODE', 'NATIVELY_AUTOSTART_MEETING', 'NATIVELY_CAPTURE_PROMPTS',
  'NATIVELY_QUESTION_DETECTION_MODEL', 'NATIVELY_FIRST_TOKEN_TIMEOUT_MS', 'NATIVELY_TURN_GATE_MS', 'NATIVELY_TURN_SETTLE_MS',
  'NATIVELY_TURN_UNFINISHED_HOLD_MS', 'NATIVELY_TURN_CONTINUATION_MS', 'NATIVELY_TURN_MAX_HOLD_MS', 'NATIVELY_TURN_WORDLESS_GRACE_MS',
  'NATIVELY_DETECTOR_CALIBRATE', 'NATIVELY_DETECTOR_CHAIN_TEST', 'NATIVELY_DETECTOR_CHAIN_TEST_QUESTIONS', 'NATIVELY_GEMMA_TTFT_MS',
  'NATIVELY_GEMMA_MAX_ATTEMPTS', 'NATIVELY_GEMMA_VISION_TTFT_MS', 'NATIVELY_GEMMA_VISION_TTFT_BASE_MS', 'NATIVELY_GEMMA_VISION_TTFT_PER_IMAGE_MS',
  'NATIVELY_GEMMA_VISION_MAX_ATTEMPTS', 'NATIVELY_API_URL', 'NATIVELY_BUILD_ALL_MAC_ARCHES', 'I60_PROBE_DEADLINE_MIN',
  'NATIVELY_EARLIER_QUESTION', 'NATIVELY_FLIGHT_ARMS', 'NATIVELY_SCENARIOS'];

const NODE = '"C:\\Program Files\\nodejs\\node.exe"';
const RUN = 'electron\\test\\golden\\interview60.run.mjs';
const LOG = 'electron\\test\\golden\\interview60.runs\\router-smoke.launcher.log';
const ERR = '"%TEMP%\\natively-router-smoke-launcher-error.log"';

const lines = [
  '@echo off',
  'rem Router-default smoke, plan Task 17: the whole live40.wav hour with the router on, run label router-smoke. App hour only, no flight.mjs, so FLIGHT_FOCUSED is not set.',
  'rem Generated by gen-launch-router-smoke.mjs, which reads the bytes back. Never edit this file by hand and never with sed.',
  'rem No key wrapper: like launch-eq.cmd, the app reads its own credentials. No key is read or printed here.',
  'rem Exit codes: 9 MAIN not found or wrong folder, 8 live40.wav missing, 6 harness does not stop the app, 5 wav:check failed, then the auto run own exit code.',
  'rem NOTE ON STYLE: no parentheses inside any echo in an if-block.',
  'rem MAIN sits under a non-ASCII folder name: found by wildcard so this file stays ASCII.',
  'for /d %%D in ("%USERPROFILE%\\OneDrive\\Masa*") do if exist "%%D\\natively-cluely-ai-assistant\\.git" cd /d "%%D\\natively-cluely-ai-assistant"',
  `if not exist "${RUN}" (`,
  `  echo wrong working directory: %CD% >> ${ERR}`,
  '  exit /b 9',
  ')',
  'if not exist "electron\\test\\golden\\live40.wav" (',
  `  echo live40.wav missing - build the audio first >> ${ERR}`,
  '  exit /b 8',
  ')',
  `findstr /C:"process.on('exit', appStop)" "${RUN}" >nul 2>&1`,
  'if not "%errorlevel%"=="0" (',
  `  echo the harness does not stop the app when a run ends >> ${ERR}`,
  '  exit /b 6',
  ')',
  ...SET.map((s) => `set ${s}`),
  ...CLEAR.map((n) => `set ${n}=`),
  `echo === LAUNCHER router-smoke start %DATE% %TIME% === >> ${LOG}`,
  `${NODE} ${RUN} wav:check >> ${LOG} 2>&1`,
  'if not "%errorlevel%"=="0" (',
  `  echo live40.wav does not match the live40 roster - see router-smoke.launcher.log >> ${ERR}`,
  '  exit /b 5',
  ')',
  `${NODE} ${RUN} auto router-smoke >> ${LOG} 2>&1`,
  'set SMOKE_EXIT=%errorlevel%',
  `echo === SMOKE EXIT %SMOKE_EXIT% %DATE% %TIME% === >> ${LOG}`,
  `${NODE} ${RUN} app:stop >> ${LOG} 2>&1`,
  `echo === LAUNCHER router-smoke done %DATE% %TIME% === >> ${LOG}`,
  'exit /b %SMOKE_EXIT%',
];

// lint: balanced if-blocks, no unexpanded placeholders, ASCII, no trailing space, no specials in echoes inside blocks
const bad = [];
let depth = 0;
lines.forEach((l, i) => {
  const at = `line ${i + 1}`;
  if (!/^[\x20-\x7e]*$/.test(l)) bad.push(`${at}: non-ASCII`);
  if (/\s$/.test(l)) bad.push(`${at}: trailing whitespace`);
  if (/\{\{|\}\}|@@/.test(l)) bad.push(`${at}: unexpanded placeholder`);
  if (/^rem\s/i.test(l) && /[%()&|<>^]/.test(l)) bad.push(`${at}: rem line holds a special character`);
  if (/\d>>/.test(l)) bad.push(`${at}: digit before >>`);
  if (depth > 0 && /^\s*echo /i.test(l)) {
    const msg = l.trimStart().slice(5).split(' >> ')[0].split('%CD%').join('');
    if (/[()&|<>^%!"]/.test(msg)) bad.push(`${at}: echo in if-block holds a special character`);
  }
  if (/^if .*\($/i.test(l)) depth++;
  else if (l === ')') { depth--; if (depth < 0) bad.push(`${at}: unmatched )`); }
});
if (depth !== 0) bad.push('an if-block is never closed');
if (bad.length) { console.log('REFUSED: lint failed, nothing written'); bad.forEach((b) => console.log('  ' + b)); process.exit(2); }

fs.writeFileSync(FILE, Buffer.from(lines.join('\r\n') + '\r\n', 'latin1'));
const buf = fs.readFileSync(FILE);
let crlf = 0, bareLf = 0, bareCr = 0, high = 0;
for (let i = 0; i < buf.length; i++) {
  const c = buf[i];
  if (c === 0x0d) { if (buf[i + 1] === 0x0a) { crlf++; i++; } else bareCr++; } else if (c === 0x0a) bareLf++; else if (c > 0x7e) high++;
}
const got = buf.toString('latin1').split('\r\n'); got.pop();
const same = got.length === lines.length && got.every((l, i) => l === lines[i]);
const ok = same && bareLf === 0 && bareCr === 0 && high === 0 && crlf === lines.length;
console.log(`${FILE}: ${buf.length} bytes, ${lines.length} lines, CRLF ${crlf}, bare LF ${bareLf}, bare CR ${bareCr}, above 126 ${high}, readback equal ${same}`);
console.log(ok ? 'GENERATOR: PASS' : 'GENERATOR: FAIL');
process.exit(ok ? 0 : 1);
