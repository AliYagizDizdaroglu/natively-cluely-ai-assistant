// gen-launchers-b1.mjs: writes the four bundle-1 launchers and reads each back byte by byte:
//   bundle-1\smoke\launch-b1-smoke.cmd   bundle-1\smoke\launch-b1-smoke-dry.cmd     (the app smoke with the fault drill, tonight)
//   bundle-1\flight\launch-b1-flight.cmd bundle-1\flight\launch-b1-flight-dry.cmd   (the final flight, unregistered, no drill)
// Derived from SP\router-default\flight\launch-rd.cmd / launch-rd-dry.cmd (the guard chain and its exit codes) and SP\router-default\launch-router-smoke.cmd (the
// app-hour-only smoke: wav:check, then run.mjs auto <label>). A flight and its dry twin are composed from ONE common section so they cannot drift apart.
// ASCII, CRLF, never edited by hand and never with sed (tooling_flight_launchers). T is NOT baked in: the task passes it as the first argument (register-b1.ps1).
//   node gen-launchers-b1.mjs [--commit <40 hex>] [--extra <n>] [--ctx-sha12 <12 hex>] [--out <dir>]   (--out writes all four into one folder, for calibration)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const COMMIT = opt('--commit', '9d5bd9ea411dd4069f5367e7b4447ea263ec9aa1');
const EXTRA = opt('--extra', '150');
const CTX = opt('--ctx-sha12', 'b2a43a2159a2');
if (!/^[0-9a-f]{40}$/.test(COMMIT)) { console.error('--commit must be 40 lowercase hex'); process.exit(2); }
if (!/^\d{1,4}$/.test(EXTRA)) { console.error('--extra must be a whole number'); process.exit(2); }
if (!/^[0-9a-f]{12}$/.test(CTX)) { console.error('--ctx-sha12 must be 12 lowercase hex'); process.exit(2); }
const outDir = opt('--out', null);
const SMOKE_DIR = outDir ? path.resolve(outDir) : HERE;
const FLIGHT_DIR = outDir ? path.resolve(outDir) : path.resolve(HERE, '..', 'flight');

const NODE = '"C:\\Program Files\\nodejs\\node.exe"';
const RUN = 'electron\\test\\golden\\interview60.run.mjs';
const FLIGHT = 'electron\\test\\golden\\interview60.flight.mjs';
const RUNS = 'electron\\test\\golden\\interview60.runs';
// the names the router smoke / rd launchers clear, minus the ones this launcher sets
const CLEAR = ['NATIVELY_GEMINI_THINKING_LEVEL', 'NATIVELY_VERBAL_PRIMARY_MODEL', 'NATIVELY_VERBAL_HEDGE', 'NATIVELY_VERBAL_HEDGE_TRIGGER_MS',
    'NATIVELY_FOLLOWUP_PARENT', 'NATIVELY_LIVE_MODEL', 'NATIVELY_LIVE_MODE', 'NATIVELY_CAPTURE_PROMPTS',
    'NATIVELY_QUESTION_DETECTION_MODEL', 'NATIVELY_FIRST_TOKEN_TIMEOUT_MS', 'NATIVELY_TURN_GATE_MS', 'NATIVELY_TURN_SETTLE_MS',
    'NATIVELY_TURN_UNFINISHED_HOLD_MS', 'NATIVELY_TURN_CONTINUATION_MS', 'NATIVELY_TURN_MAX_HOLD_MS', 'NATIVELY_TURN_WORDLESS_GRACE_MS',
    'NATIVELY_DETECTOR_CALIBRATE', 'NATIVELY_DETECTOR_CHAIN_TEST', 'NATIVELY_DETECTOR_CHAIN_TEST_QUESTIONS', 'NATIVELY_GEMMA_TTFT_MS',
    'NATIVELY_GEMMA_MAX_ATTEMPTS', 'NATIVELY_GEMMA_VISION_TTFT_MS', 'NATIVELY_GEMMA_VISION_TTFT_BASE_MS', 'NATIVELY_GEMMA_VISION_TTFT_PER_IMAGE_MS',
    'NATIVELY_GEMMA_VISION_MAX_ATTEMPTS', 'NATIVELY_API_URL', 'NATIVELY_BUILD_ALL_MAC_ARCHES', 'NATIVELY_EARLIER_QUESTION', 'NATIVELY_SCENARIOS'];

function build(kind, dry) {
    const smoke = kind === 'smoke';
    const base = smoke ? 'Natively-smoke-b1' : 'Natively-flight-b1';
    const label = smoke ? 'b1-smoke' : 'b1-final';
    const stem = `b1-${kind}${dry ? '-dry' : ''}`;                    // log / error-log stem
    const LOG = `${RUNS}\\${stem}.launcher.log`;
    const OBS = `${RUNS}\\${stem}.observe.log`;
    const OBSSTOP = `${RUNS}\\${stem}.observe.stop`;
    const ERR = `"%TEMP%\\natively-b1-${kind}-launcher-error.log"`;
    const S = smoke ? '%~dp0' : '%~dp0..\\smoke\\';                      // where guard-b1, b1-proofs, observe-session and read-smoke-b1 live
    const L = [];
    const rem = (t) => L.push('rem ' + t);
    L.push('@echo off');
    rem(smoke
        ? `${dry ? 'DRY twin of launch-b1-smoke.cmd, task Natively-smoke-b1-dry: every check of the real launcher except the precheck stamp and the clock window, then it stops. No app, no audio, no model call.' : 'Bundle-1 app smoke with the fault drill, task Natively-smoke-b1: the whole live40.wav hour, router flag ON, NATIVELY_FAULT_DRILL armed (SPEC-bundle-1 7.4, AMENDMENT-A1 section 3), run label b1-smoke. App hour only, no flight.mjs.'}`
        : `${dry ? 'DRY twin of launch-b1-flight.cmd, task Natively-flight-b1-dry: every check of the real launcher except the precheck stamp and the clock window, then it stops. No app, no audio, no model call.' : 'Bundle-1 final flight, task Natively-flight-b1 (UNREGISTERED until the user picks a time, register-b1.ps1 -Which flight): live40, router ON, NO fault drill, arms high,low,captured-high as r1 flew, run label b1-final.'}`);
    rem('Generated by gen-launchers-b1.mjs, which reads the bytes back. Never edit this file by hand and never with sed: change the generator and re-run it.');
    rem('Derived from router-default launch-rd.cmd and launch-router-smoke.cmd: same guard chain, same exit codes. No key wrapper: the app reads its own credentials; no key is read or printed here.');
    rem('T arrives as the FIRST ARGUMENT from the task action, as yyyy-MM-dd HH:mm local +03:00: the guard checks the clock against it, the night gates read it.');
    rem('Exit codes: 9 wrong folder, 8 audio missing, 7 roster missing, 6 harness does not stop the app, 12 commit not a full hash, 13 T argument missing, 11 a b1 tool missing, 5 wav:check failed, 3 dist proofs failed before or after the run, 4 guard failed' + (dry ? ', 0 every check passed.' : ', then the run own exit code, then the smoke read verdict.'));
    rem('NOTE ON STYLE: no parentheses inside any echo in an if-block. On 2026-09-20 a guard message citing a commit in parentheses closed its own if-block early and a flight died before takeoff with no log.');
    rem('MAIN sits under a non-ASCII folder name: found by wildcard so this file stays ASCII. The error log must not exist at arming.');
    L.push('for /d %%D in ("%USERPROFILE%\\OneDrive\\Masa*") do if exist "%%D\\natively-cluely-ai-assistant\\.git" cd /d "%%D\\natively-cluely-ai-assistant"');
    const block = (cond, msg, code) => { L.push(`if ${cond} (`); L.push(`  echo ${msg} >> ${ERR}`); L.push(`  exit /b ${code}`); L.push(')'); };
    block('not exist "electron\\test\\golden\\interview60.flight.mjs"', 'wrong working directory: %CD%', 9);
    block('not exist "electron\\test\\golden\\live40.wav"', 'live40.wav missing - build the audio first', 8);
    block('not exist "electron\\test\\golden\\live40.questions.mjs"', 'live40 roster missing from this checkout', 7);
    rem('Guard: the harness must stop the app when a run ends - 5952b23.');
    L.push(`findstr /C:"process.on('exit', appStop)" "electron\\test\\golden\\interview60.run.mjs" >nul 2>&1`);
    block('not "%errorlevel%"=="0"', 'the harness does not stop the app when a run ends - pick 5952b23 into this checkout', 6);
    block(`not exist "${S}guard-b1.mjs"`, 'a b1 tool is missing: guard-b1.mjs', 11);
    block(`not exist "${S}b1-proofs.mjs"`, 'a b1 tool is missing: b1-proofs.mjs', 11);
    if (!dry) {
        block(`not exist "${S}observe-session.ps1"`, 'a b1 tool is missing: observe-session.ps1', 11);
        if (smoke) { block(`not exist "${S}read-smoke-b1.mjs"`, 'a b1 tool is missing: read-smoke-b1.mjs', 11); block(`not exist "${S}..\\check-smoke-cues.mjs"`, 'a b1 tool is missing: check-smoke-cues.mjs', 11); }
    }
    rem('T: the first argument. An empty one refuses before anything runs.');
    L.push('set NATIVELY_B1_T=%~1');
    block('"%NATIVELY_B1_T%"==""', 'no T argument - the task passes T as yyyy-MM-dd HH:mm', 13);
    rem('The environment. A set with no value UNSETS the name in cmd. Cleared: every model, level, hedge, earlier-question, follow-up, turn, Gemma and test-chain override. Set: this run own names.');
    L.push('set NATIVELY_STT_PROVIDER=deepgram');
    L.push('set NATIVELY_LIVE_ROUTER=1');
    L.push('set NATIVELY_ROSTER=live40');
    L.push(`set NATIVELY_B1_KIND=${kind}`);
    L.push(`set NATIVELY_B1_TASK=${base}`);
    L.push(`set NATIVELY_B1_EXTRA_REQUESTS=${EXTRA}`);
    L.push('set I60_PROBE_DEADLINE_MIN=35');
    if (smoke) {
        rem('The drill: seconds after meeting start, NO space after the comma (faultDrill.ts splits on the comma and does not trim). router-drop at 600 s, ear-mute at 750 s: the wav plays about 1140 s of questions, about 110 s after the meeting starts, so the spec 1500 s would fall after the last question.');
        L.push('set NATIVELY_FAULT_DRILL=router-drop@600,ear-mute@750');
        rem('NATIVELY_AUTOSTART_MEETING is the harness-only start; run.mjs app:start sets it to 1 for the app, and the drill is honoured only with it. Set here so the guard parses the drill exactly as the app will.');
        L.push('set NATIVELY_AUTOSTART_MEETING=1');
        L.push('set NATIVELY_FLIGHT_ARMS=');
    } else {
        rem('The final flight runs NO drill (spec 7.1): the variable is unset here and the guard refuses any value of it. The arms, the focused arms and the router context sha are r1 own (the guard and the harness preflight check them).');
        L.push('set NATIVELY_FAULT_DRILL=');
        L.push('set NATIVELY_AUTOSTART_MEETING=');
        L.push('set NATIVELY_FLIGHT_ARMS=high,low,captured-high');
        L.push('set NATIVELY_FLIGHT_FOCUSED=off');
        L.push(`set NATIVELY_ROUTER_CONTEXT_SHA12=${CTX}`);
    }
    for (const n of CLEAR) L.push(`set ${n}=`);
    L.push(`set NATIVELY_FLIGHT_COMMIT=${COMMIT}`);
    rem('The commit check: 40 lowercase hex characters, nothing else; the length is tested by substring because findstr cannot count to 40.');
    L.push('set COMMIT_OK=1');
    L.push('echo %NATIVELY_FLIGHT_COMMIT%| findstr /R /X "[0-9a-f][0-9a-f]*" >nul 2>&1');
    L.push('if errorlevel 1 set COMMIT_OK=0');
    L.push('if "%NATIVELY_FLIGHT_COMMIT:~39,1%"=="" set COMMIT_OK=0');
    L.push('if not "%NATIVELY_FLIGHT_COMMIT:~40,1%"=="" set COMMIT_OK=0');
    block('"%COMMIT_OK%"=="0"', 'NATIVELY_FLIGHT_COMMIT is not a full 40 character hash - run gen-launchers-b1.mjs with the commit', 12);
    L.push(`echo === LAUNCHER ${stem} start %DATE% %TIME% commit %NATIVELY_FLIGHT_COMMIT% T %NATIVELY_B1_T% === >> ${LOG}`);
    L.push(`certutil -hashfile "%~f0" SHA256 >> ${LOG} 2>&1`);
    rem('Guard: the audio must hold exactly the roster clips and gaps. NATIVELY_ROSTER=live40 was set above.');
    L.push(`${NODE} ${RUN} wav:check >> ${LOG} 2>&1`);
    block('not "%errorlevel%"=="0"', `live40.wav does not match the live40 roster - see ${stem}.launcher.log`, 5);
    rem('Dist proofs 1: the reduced bundle markers and shas, and the sha256 of the proof files, printed into the log. The root is passed in full: a relative root fails.');
    L.push(`echo === DIST BEFORE THE RUN === >> ${LOG}`);
    L.push(`${NODE} "${S}b1-proofs.mjs" --root "%CD%" >> ${LOG} 2>&1`);
    block('not "%errorlevel%"=="0"', `dist proofs 1 failed - see ${stem}.launcher.log`, 3);
    rem(`BEHAVIOURAL guard: ${dry ? 'the dry form, no precheck stamp and no clock window' : 'with the precheck stamp and the clock window'}. Calibrated by breaking each premise once, see guard-b1-cal.txt.`);
    L.push(`${NODE} "${S}guard-b1.mjs" --kind ${kind}${dry ? ' --dry' : ' --require-precheck'} >> ${LOG} 2>&1`);
    block('not "%errorlevel%"=="0"', `behavioural guard failed - see ${stem}.launcher.log`, 4);
    if (dry) {
        L.push(`echo === LAUNCHER ${stem} done GUARD OK %DATE% %TIME% === >> ${LOG}`);
        L.push('exit /b 0');
        return L;
    }
    rem('Observability: a read-only sampler records the console session, the electron session ids and the visible electron windows every 20 s. It stops on the stop file or after 120 min, and is stopped below.');
    L.push(`del "${OBSSTOP}" >nul 2>&1`);
    L.push(`start "" /b powershell -NoProfile -ExecutionPolicy Bypass -File "${S}observe-session.ps1" -Out "${OBS}" -Stop "${OBSSTOP}" -EverySec 20 -MaxMin 120 >nul 2>&1`);
    if (smoke) {
        rem('The smoke itself: build, start, probe, preflight, the hour, snapshot, gate, stop. It stops the app by itself when it ends: process.on exit appStop, 5952b23.');
        L.push(`${NODE} ${RUN} auto ${label} >> ${LOG} 2>&1`);
    } else {
        rem('The flight itself. It stops the app by itself when it ends: process.on exit appStop, 5952b23.');
        L.push(`${NODE} ${FLIGHT} ${label} >> ${LOG} 2>&1`);
    }
    L.push('set RUN_EXIT=%errorlevel%');
    L.push(`echo === RUN EXIT %RUN_EXIT% %DATE% %TIME% === >> ${LOG}`);
    L.push(`${NODE} ${RUN} app:stop >> ${LOG} 2>&1`);
    L.push(`echo stop > "${OBSSTOP}"`);
    rem('Dist proofs 2: the run rebuilds the dist when any electron source is newer than the oldest output, so THIS is the dist that ran. Each proof file sha256 must equal the one printed before the run, else the run is VOID.');
    L.push(`echo === DIST AFTER THE RUN === >> ${LOG}`);
    L.push(`${NODE} "${S}b1-proofs.mjs" --root "%CD%" --same-as-log ${LOG} >> ${LOG} 2>&1`);
    block('not "%errorlevel%"=="0"', `dist proofs 2 failed - the dist that ran is not the proven build - see ${stem}.launcher.log`, 3);
    if (smoke) {
        rem('The smoke read: check-smoke-cues v5, the 7.4 bars, the drill evidence and the observability row, into bundle-1\\smoke\\SMOKE-READ.txt. Ids, counts and log-line names only. No model call.');
        L.push(`${NODE} "${S}read-smoke-b1.mjs" --label ${label} --observe "${OBS}" >> ${LOG} 2>&1`);
        L.push('set READ_EXIT=%errorlevel%');
        L.push(`echo === SMOKE READ EXIT %READ_EXIT% %DATE% %TIME% === >> ${LOG}`);
        L.push('if not "%RUN_EXIT%"=="0" exit /b %RUN_EXIT%');
        L.push('exit /b %READ_EXIT%');
    } else {
        L.push(`echo === LAUNCHER ${stem} done %DATE% %TIME% === >> ${LOG}`);
        L.push('exit /b %RUN_EXIT%');
    }
    return L;
}

function emit(dir, name, lines) {
    fs.mkdirSync(dir, { recursive: true });
    const text = lines.join('\r\n') + '\r\n';
    // ---- checks before writing: ASCII, no placeholder, no parenthesis in an echo inside an if-block
    if (/[^\x20-\x7e\r\n]/.test(text)) throw new Error(`${name}: non-ASCII character`);
    let inBlock = false;
    lines.forEach((l, i) => {
        if (/^if .*\($/.test(l)) inBlock = true;
        else if (l === ')') inBlock = false;
        else if (inBlock && /^\s+echo /.test(l) && /[()]/.test(l.replace(/>> "%TEMP%\\[^"]*"/, ''))) throw new Error(`${name} line ${i + 1}: parenthesis in an echo inside an if-block: ${l}`);
    });
    const file = path.join(dir, name);
    fs.writeFileSync(file, text, 'latin1');
    const back = fs.readFileSync(file);
    const crs = [...back].filter((b) => b === 13).length;
    if (back.toString('latin1') !== text) throw new Error(`${name}: read-back differs`);
    if (crs !== lines.length) throw new Error(`${name}: CR count ${crs} != line count ${lines.length}`);
    if ([...back].some((b) => b > 126 || (b < 32 && b !== 10 && b !== 13))) throw new Error(`${name}: non-ASCII byte after write`);
    console.log(`wrote ${file}  ${lines.length} lines  CR ${crs}`);
}
emit(SMOKE_DIR, 'launch-b1-smoke.cmd', build('smoke', false));
emit(SMOKE_DIR, 'launch-b1-smoke-dry.cmd', build('smoke', true));
emit(FLIGHT_DIR, 'launch-b1-flight.cmd', build('flight', false));
emit(FLIGHT_DIR, 'launch-b1-flight-dry.cmd', build('flight', true));
