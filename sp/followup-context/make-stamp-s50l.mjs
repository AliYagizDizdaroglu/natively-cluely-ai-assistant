// Generates stamp-s50l.mjs from the registered stamp.mjs (amendment item 24, review M4): the same checks over the s50l
// material — the recorded hashes, ARMS (userB = userA + block at the marker), the 46-entry s50l parity fixture
// re-derived by the hashed selector, and the corrupted-parent check. Only the three file names are swapped; each
// anchor must match exactly once. Run with cwd = followup-context (stamp.mjs resolves its files relative to the cwd).
import fs from 'node:fs';
const HERE = new URL('.', import.meta.url);
let s = fs.readFileSync(new URL('stamp.mjs', HERE), 'utf8');
const swaps = [
    ["for (const f of ['earlierQuestions.ref.mjs', 'gate-report.mjs', 's50m-gated.json', 'parity-fixture.json'])", "for (const f of ['earlierQuestions.ref.mjs', 'gate-report-s50l.mjs', 's50l-gated.json', 's50l-parity-fixture.json'])"],
    ["const out = JSON.parse(fs.readFileSync('s50m-gated.json', 'utf8'));", "const out = JSON.parse(fs.readFileSync('s50l-gated.json', 'utf8'));"],
    ["const fx = JSON.parse(fs.readFileSync('parity-fixture.json', 'utf8'));", "const fx = JSON.parse(fs.readFileSync('s50l-parity-fixture.json', 'utf8'));"],
];
for (const [a, b] of swaps) {
    const n = s.split(a).length - 1;
    if (n !== 1) { console.log(`REFUSED: anchor found ${n} times: ${a.slice(0, 80)}`); process.exit(2); }
    s = s.replace(a, b);
}
s = `// GENERATED by make-stamp-s50l.mjs from stamp.mjs (s50l file names only). Do not edit.\n${s}`;
fs.writeFileSync(new URL('stamp-s50l.mjs', HERE), s);
console.log('wrote stamp-s50l.mjs');
