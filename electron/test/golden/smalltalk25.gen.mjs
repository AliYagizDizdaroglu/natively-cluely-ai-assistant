/**
 * Generates smalltalk25.questions.mjs from natively-lab\sp\smalltalk\items.json.
 *
 *   node electron/test/golden/smalltalk25.gen.mjs [--items <items.json>]
 *
 * Refuses (exit 2) any items.json whose sha256 is not the pinned one: the roster is a stimulus,
 * and a silently different one would make every smalltalk25 hour incomparable with the others.
 *
 * Output order is items.json's, which is the play order. A follow-up whose parent does not
 * precede it, an unknown `expect`, an ignore item without a `talk` or an answer item without a
 * `role` refuses with exit 1 rather than writing a roster the reader would misread.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ITEMS_SHA256 = '52bdab3db973059e6d2f171464b82b3e588bf3e97782f16168b70954bed81c2c';
const DEFAULT_ITEMS = 'C:\\Users\\sotka\\OneDrive\\Masaüstü\\natively-lab\\sp\\smalltalk\\items.json';
// 20 s on every item: the same gap as live40 (worst close 16 s + 2 s pairing window + 2 s margin).
const GAP_MS = 20000;

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const itemsPath = flag('--items') ?? DEFAULT_ITEMS;
const outPath = path.join(HERE, 'smalltalk25.questions.mjs');

const raw = fs.readFileSync(itemsPath);
const sha = crypto.createHash('sha256').update(raw).digest('hex');
if (sha !== ITEMS_SHA256) {
    console.error(`items.json sha256 ${sha} refused (expected ${ITEMS_SHA256})`);
    process.exit(2);
}

const src = JSON.parse(raw.toString('utf8'));
const ids = src.items.map((x) => x.id);
const pos = new Map(ids.map((id, i) => [id, i]));
const problems = [];
if (src.items.length !== 25) problems.push(`expected 25 items, found ${src.items.length}`);
if (new Set(ids).size !== ids.length) problems.push('duplicate ids');
for (const x of src.items) {
    if (x.expect !== 'ignore' && x.expect !== 'answer') problems.push(`${x.id}: expect is ${JSON.stringify(x.expect)}, not ignore | answer`);
    if (x.expect === 'ignore' && x.talk !== 'smalltalk-question' && x.talk !== 'smalltalk-statement') problems.push(`${x.id}: an ignore item needs talk smalltalk-question | smalltalk-statement`);
    if (x.expect === 'answer' && !['behavioral', 'technical', 'followup', 'closing', 'embedded'].includes(x.role)) problems.push(`${x.id}: an answer item needs a role`);
    if (x.parent != null && !(pos.has(x.parent) && pos.get(x.parent) < pos.get(x.id))) problems.push(`${x.id}: parent ${x.parent} does not precede it`);
    if ((x.role === 'followup') !== (x.parent != null)) problems.push(`${x.id}: role followup and parent must go together`);
}
if (problems.length) {
    console.error(`smalltalk25 items refused:\n  ${problems.join('\n  ')}`);
    process.exit(1);
}

// `kind` is deliberately NOT set: the harness reads kind === 'spoken' (the default) to tell a spoken item from a
// screenshot cue (metrics.mjs, judge.mjs), so the small-talk shape lives in `talk` instead.
const items = src.items.map((x) => ({
    id: x.id,
    q: x.text,
    gapMs: GAP_MS,
    expect: x.expect,
    ...(x.talk ? { talk: x.talk } : {}),
    ...(x.role ? { role: x.role } : {}),
    // The harness's own convention (live40.gen.mjs): a follow-up has level 'followup' and chain = its PARENT's item id.
    ...(x.parent ? { chain: x.parent, parent: x.parent } : {}),
    level: x.parent ? 'followup' : 'main',
    topic: x.expect === 'ignore' ? 'smalltalk' : x.role,
}));

const out = `/**
 * GENERATED by smalltalk25.gen.mjs from natively-lab\\sp\\smalltalk\\items.json
 * (sha256 ${ITEMS_SHA256}). Do not edit: re-run the generator.
 *
 * 25 items in play order: 14 \`expect: 'ignore'\` (small talk and logistics; \`talk\` is 'smalltalk-question'
 * for the question-shaped ones, 'smalltalk-statement' otherwise) and 11 \`expect: 'answer'\` (real interview
 * questions; \`role\` is behavioral | technical | followup | closing | embedded). A follow-up has \`level\`
 * 'followup' and \`chain\` = \`parent\` = the technical main it follows; the rest are level 'main'.
 * Every gap is 20 s (as live40); the audio is rendered once with SAPI 'Microsoft David Desktop' and copied
 * in by smalltalk25.clips.mjs. \`kind\` is left unset on purpose (the harness reads it as spoken | screenshot).
 */
export const SMALLTALK25 = ${JSON.stringify(items, null, 4)};
`;
fs.writeFileSync(outPath, out);
console.log(`wrote ${path.basename(outPath)}  ${items.length} items  source sha256 ${ITEMS_SHA256.slice(0, 12)}`);
